import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import type projectConfig from '../project.json';

type Project = typeof projectConfig;
type ExtensionConfig = { languages: unknown[]; [key: string]: unknown };

const json = (value: unknown) => `${JSON.stringify(value, null, 4)}\n`;

function withPythonProjectMetadata(contents: string, addon: Project['artifacts']['ankiAddon']): string {
    const values = { name: addon.package, version: addon.version };
    let inProject = false;
    const replacements = { name: 0, version: 0 };
    const updated = contents
        .split('\n')
        .map((line) => {
            if (/^\s*\[/.test(line)) inProject = /^\s*\[project\]\s*(?:#.*)?$/.test(line);
            if (!inProject) return line;
            const field = /^(\s*(name|version)\s*=\s*)(?:"[^"]*"|'[^']*')(\s*(?:#.*)?)$/.exec(line);
            if (!field) return line;
            const key = field[2] as keyof typeof values;
            replacements[key]++;
            return `${field[1]}${JSON.stringify(values[key])}${field[3]}`;
        })
        .join('\n');
    for (const [key, count] of Object.entries(replacements)) {
        if (count !== 1) throw new Error(`Expected exactly one [project] ${key} in plugins/anki/pyproject.toml`);
    }
    return updated;
}

export function generatedProjectFiles(project: Project, extensionConfig: ExtensionConfig): Record<string, string> {
    const { webSocket, ankiConnect } = project.services;
    return {
        'common/extension.json': json({
            ...extensionConfig,
            latest: {
                version: project.publishedVersion,
                url: `${project.urls.repo}/releases/tag/${encodeURIComponent(project.artifacts.extension.tagPrefix + project.publishedVersion)}`,
            },
        }),
        'plugins/anki/asbplayer-addon/config.json': json({
            enabled: true,
            port: webSocket.port,
            postMineAction: webSocket.postMineAction,
        }),
        'plugins/anki/asbplayer-addon/manifest.json': json({
            package: project.artifacts.ankiAddon.package,
            name: project.names.short,
            human_version: project.artifacts.ankiAddon.version,
        }),
        'plugins/anki/asbplayer-addon/config.md': [
            '<!-- Generated by scripts/sync-project-config.ts; DO NOT EDIT. -->',
            `# ${project.names.short} Add-on Configuration`,
            '',
            `Configure the WebSocket server for one-click mining with ${project.names.short}.`,
            '',
            '## Settings',
            '',
            '- **enabled**: Enable (`true`) or disable (`false`) the WebSocket server (default: `true`).',
            '',
            `- **port**: WebSocket server port (default: \`${webSocket.port}\`). Must match ${project.names.short}'s "WebSocket Server URL" setting (in misc settings). The default URL is \`ws://${webSocket.host}:${webSocket.port}${webSocket.path}\`.`,
            '',
            `- **postMineAction**: Action to perform after mining a word (default: \`${webSocket.postMineAction}\`):`,
            '    - `0` = None',
            '    - `1` = Open Anki dialog',
            '    - `2` = Update last card',
            '',
        ].join('\n'),
        'scripts/web-socket-server/project_config.go': [
            '// Code generated by scripts/sync-project-config.ts; DO NOT EDIT.',
            '',
            'package main',
            '',
            `const defaultWebSocketPort = ${JSON.stringify(String(webSocket.port))}`,
            `const defaultWebSocketPath = ${JSON.stringify(webSocket.path)}`,
            `const defaultAnkiConnectURL = ${JSON.stringify(`http://${ankiConnect.host}:${ankiConnect.port}`)}`,
            `const defaultPostMineAction = ${JSON.stringify(String(webSocket.postMineAction))}`,
            '',
        ].join('\n'),
        'scripts/web-socket-server/.env.example': [
            '# Generated by scripts/sync-project-config.ts. Copy to .env to configure the proxy.',
            '',
            '# Port that the proxy will listen on',
            `PORT=${webSocket.port}`,
            '',
            '# AnkiConnect URL',
            `ANKI_CONNECT_URL=http://${ankiConnect.host}:${ankiConnect.port}`,
            '',
            '# Action for asbplayer to take when the proxy receives an addNote request',
            "# 0 = 'None'",
            "# 1 = 'Open Anki dialog'",
            "# 2 = 'Update last card' (updates last card with asbplayer media AFTER passing through original addNote request)",
            "# 3 = 'Export card'",
            `POST_MINE_ACTION=${webSocket.postMineAction}`,
            '',
        ].join('\n'),
    };
}

/** Check or update packaged config without requiring the repository at runtime. */
export function syncProjectConfig(root: string, check = false): string[] {
    const project: Project = JSON.parse(readFileSync(join(root, 'project.json'), 'utf8'));
    const extensionConfig: ExtensionConfig = JSON.parse(readFileSync(join(root, 'common/extension.json'), 'utf8'));
    const generated = generatedProjectFiles(project, extensionConfig);
    const pythonProject = 'plugins/anki/pyproject.toml';
    generated[pythonProject] = withPythonProjectMetadata(
        readFileSync(join(root, pythonProject), 'utf8'),
        project.artifacts.ankiAddon
    );
    const stale: string[] = [];
    for (const [relativePath, contents] of Object.entries(generated)) {
        const path = join(root, relativePath);
        let existing: string | undefined;
        try {
            existing = readFileSync(path, 'utf8');
        } catch (error) {
            if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
        }
        if (existing === contents) continue;
        stale.push(relativePath);
        if (!check) {
            mkdirSync(dirname(path), { recursive: true });
            writeFileSync(path, contents);
        }
    }
    return stale;
}

